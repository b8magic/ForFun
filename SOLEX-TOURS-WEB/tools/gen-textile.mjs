// Fret: the interlocking key woven into the rolled blankets (cream on mauve, red/sun edges).
const fret = (() => {
  const unit = ['ccccc.', 'c...c.', 'c.c.c.', 'c.ccc.', 'c.....', 'cccccc'];
  const W = 24, rep = (s) => s.repeat(4).replace(/\./g, 'm');
  return ['r'.repeat(W), 'y'.repeat(W), 'm'.repeat(W), ...unit.map(rep), 'm'.repeat(W), 'y'.repeat(W), 'r'.repeat(W)].join('\n');
})();

// Volcano band: the logo's twin peaks and sun as 1-stitch stairs on the logo sky.
const peaks = (() => {
  const W = 30, H = 16;
  const g = Array.from({ length: H }, () => Array(W).fill('s'));
  g[0].fill('r'); g[1].fill('c'); g[H - 1].fill('r'); g[H - 2].fill('c');
  const P = (cx, top, base) => { for (let y = top; y <= base; y++) { const hw = y - top; for (let x = cx - hw; x <= cx + hw; x++) g[y][(x + W) % W] = 'k'; } };
  [[15, 2], [14, 3], [15, 3], [16, 3], [13, 4], [14, 4], [15, 4], [16, 4], [17, 4], [14, 5], [15, 5], [16, 5], [11, 3], [19, 3], [12, 2], [18, 2]].forEach(([x, y]) => (g[y][x] = 'y'));
  P(10, 4, H - 3);
  P(19, 5, H - 3);
  return g.map((r) => r.join('')).join('\n');
})();

