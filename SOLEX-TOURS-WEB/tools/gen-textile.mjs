// The selvedge and fret are on the first screen (inlined with the critical CSS); the rest load with site.css.
const CRITICAL = ['selvedge', 'fret'];
// Only the repeating bands need their stitch size in CSS (--tx-K-w/-h drive background-size); icons are
// drawn with background-size: contain, so their sizes would be dead bytes in the CSS budget.
const SIZED = new Set(['fret', 'peaks', 'rombo', 'zig']);
const block = (keys) => ':root{\n' + keys.map((k) => `--tx-${k}:${motifs[k].uri};` + (SIZED.has(k) ? `--tx-${k}-w:${motifs[k].w};--tx-${k}-h:${motifs[k].h};` : '')).join('\n') + '\n}\n';
const head = '/* generated by tools/gen-textile.mjs: woven stitch motifs (1 unit = 1 stitch) */\n';
const crit = head + block(CRITICAL), rest = head + block(Object.keys(motifs).filter((k) => !CRITICAL.includes(k)));
await writeFile(path.join(ROOT, 'src/assets/css/textile-critical.css'), crit);
await writeFile(path.join(ROOT, 'src/assets/css/textile.css'), rest);
console.log('textile', crit.length, '+', rest.length, 'bytes ·', Object.entries(motifs).map(([k, v]) => `${k} ${v.w}×${v.h}`).join(' · '));
