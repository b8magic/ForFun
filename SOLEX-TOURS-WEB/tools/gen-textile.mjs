// Woven "stitch" motifs as tiny SVG data URIs → src/assets/css/textile.css
//
//   node tools/gen-textile.mjs
//
// Each motif is a pixel map (one character = one stitch). Colours are sampled from the logo, the
// cabin walls and the blankets in the cabin video. Runs of the same colour are merged into one
// <rect>, shape-rendering is crispEdges, and every SVG is drawn at 1 unit per stitch: CSS scales
// it with background-size (2 CSS px per stitch on mobile, 3 on desktop) via --tx-NAME-w/-h.
