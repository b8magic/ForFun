// One stroked <path> per colour; each horizontal run of stitches is a 1-unit-wide line through the
// middle of its row ("M x y.5 h N", then relative "m dx dy h N"). Same pixels as filled rectangles
// (butt caps, crispEdges), about a third of the bytes. (Mixing in column runs is shorter raw but
// gzips worse, so rows only.)
function paths(grid, vertical) {
  const runs = {};
  grid.forEach((line, j) => {
    let i = 0;
    while (i < line.length) {
      const ch = line[i];
      let run = 1;
      while (i + run < line.length && line[i + run] === ch) run++;
      if (ch !== '.' && C[ch]) {
        const c = runs[ch], [x, y] = vertical ? [j, i] : [i, j], [ex, ey] = vertical ? [j, i + run] : [i + run, j];
        const seg = (vertical ? 'v' : 'h') + run;
        if (!c) runs[ch] = { d: (vertical ? `M${x}.5 ${y}` : `M${x} ${y}.5`) + seg, ex, ey };
        else { c.d += `m${x - c.ex} ${y - c.ey}${seg}`; c.ex = ex; c.ey = ey; } // relative: small integers
      }
      i += run;
    }
  });
  return Object.entries(runs).map(([ch, c]) => `<path stroke='${C[ch]}' d='${c.d}'/>`).join('');
}
function svg(map) {
  const rows = map.trim().split('\n').map((r) => r.trim());
  const h = rows.length, w = rows[0].length;
  // no width/height: every use sizes the motif explicitly or from the viewBox ratio (auto N px / contain)
  const s = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${w} ${h}' shape-rendering='crispEdges'>${paths(rows, false)}</svg>`;
  const uri = s.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');
  return { uri: `url("data:image/svg+xml,${uri}")`, w, h };
}

